import { useState } from "react";
import type { ReactNode } from "react";
import type { __Name__Entity, __Name__History } from "../../../../domains/__name__/types";
import type { HourSample } from "../../../../domains/history";
import { Blank, Key, Module, Panel, Pictogram, Screen, Today } from "../../shared/ui";
import type { FieldFootprint } from "../../shared/ui";
import { Icon__Name__, __CONST___PICT } from "./icons";
import "./__Name__Module.css";

export interface __Name__ModuleProps {
  entity: __Name__Entity;
  footprint?: FieldFootprint;
  /** Today, for the detail panel. Omit to leave its meter dark. */
  history?: __Name__History;
  onToggle: () => void;
  /** Open the detail panel on first render (stories). */
  defaultOpen?: boolean;
}

/** No history: every hour dark, none marked as now. */
const NO_HOURS: HourSample[] = Array(24).fill(null);

/**
 * One __label__ as a field module. The key switches it and its LED says it's on; the screen says ON or OFF. The name,
 * or a press and hold on the key, opens the detail panel with today. Generated by `npm run new-card -- __name__
 * --skin field`: make the screen read what this __label__ is, and give its panel its own controls.
 */
export function __Name__Module({ entity: e, footprint = "standard", history, onToggle, defaultOpen = false }: __Name__ModuleProps) {
  const [open, setOpen] = useState(defaultOpen);
  const unav = e.state === "unavailable";
  const on = e.state === "on";
  const openPanel = () => setOpen(true);

  // A plain on/off has no parameter to colour: the pictogram is neutral, and the LED says on.
  const pict = <Pictogram param="neutral" lit={on}>{__CONST___PICT}</Pictogram>;
  const read: ReactNode = unav ? <Blank label="Unavailable" /> : on ? "ON" : "OFF";
  const meta: [ReactNode, ReactNode?] | undefined = unav ? ["Unavailable", e.lastSeen ? `Seen ${e.lastSeen}` : undefined] : undefined;
  const key = (wide: boolean) => (
    <Key label={e.name} pressed={on} disabled={unav} onPress={onToggle} onHold={openPanel} caption={wide ? (on ? "On" : "Off") : undefined}>
      <Icon__Name__ />
    </Key>
  );

  return (
    <>
      <Module kind="fd-__code__" name={e.name}__areaProp__ footprint={footprint} state={e.state} onOpen={openPanel}>
        {footprint === "compact" ? (
          <>
            {key(false)}
            <Screen pict={pict}>{read}</Screen>
          </>
        ) : (
          <>
            <Screen pict={pict} meta={meta}>{read}</Screen>
            {key(true)}
          </>
        )}
      </Module>
      <Panel open={open} onClose={() => setOpen(false)} name={e.name}__areaProp__>
        <div className="fd-__code__-panel" data-state={e.state}>
          <Screen pict={pict} meta={meta}>{read}</Screen>
          {key(true)}
          <Today label="__Label__ by hour today." tone="neutral" samples={__samples__} currentHour={history?.currentHour ?? -1} />
          <p className="fd-info">
            <span>{unav ? `Last seen ${e.lastSeen ?? "unknown"}` : ""}</span>
          </p>
        </div>
      </Panel>
    </>
  );
}
